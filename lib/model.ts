// token radar — model.ts
//
// One sealed DefiLlama snapshot in, one ranked board out. The board ranks protocols that record
// no token yet: the snapshot's watchlist is the floor (every slug, always), and the early radar
// adds the strongest pre-token protocols below that floor, because finding them early is the
// board's whole point. Protocols whose token already trades are never ranked; they are listed
// apart at the market's own values.
//
// How a row's implied value is derived, from the snapshot's figures alone:
//
//   1. Start from TVL.
//   2. Multiply by the row's category multiple: the median market-cap / TVL ratio of that
//      category's live-token protocols in this same snapshot — the multiple the market itself
//      pays for the category. Categories with too few live peers use the all-category median.
//      Multiples are clamped to a band so a thin category cannot run away with the board.
//   3. Adjust for seven-day TVL growth, clamped, at half weight.
//   4. Adjust for maturity: the longer a protocol has run with no token (days since DefiLlama
//      first listed it), the closer its multiple is taken at face value.
//
// No name is ever special-cased. One function scores every row, and the dashboard recomputes
// each row from the same figures to prove the page and board.json agree.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  multiple_floor: number;
  multiple_cap: number;
  min_peers: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  multiple_floor: 0.05,
  multiple_cap: 3,
  min_peers: 3,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

export const MODEL_VERSION = 'radar-2';

/** Pre-token protocols below the watchlist floor that the early radar adds, by TVL. */
export const EARLY_ROWS = 160;

/** Live-token protocols the dashboard's Live view lists, by market cap. */
export const LIVE_ROWS = 24;

